// Run with playwright-cli run-code --filename tests/audio_workspace_check.js against the local test server.
async (page) => {
    await page.goto('http://127.0.0.1:8017/');
    await page.waitForFunction(() => document.getElementById('vision-model-select')?.value);
    await page.evaluate(() => {
        navigator.mediaDevices.getUserMedia = async () => { throw new Error('Test microphone is unavailable'); };
        document.getElementById('user-name').value = 'Audio Test';
        document.getElementById('user-company').value = 'Example';
        document.getElementById('user-role').value = 'Engineer';
        document.getElementById('user-resume').value = 'API engineer';
    });
    await page.getByRole('button', { name: 'Continue to audio setup' }).click();
    await page.waitForFunction(() => document.getElementById('audio-capture-mode').value === 'native');
    const checks = await page.evaluate(async () => {
        const assert = (condition, text) => { if (!condition) throw new Error(text); };
        const { WebSocketHandler } = await import('/static/js/websocket-handler.js');
        const { stateManager, switchView } = await import('/static/js/main.js');
        const outputs = document.getElementById('audio-output-select');
        assert(outputs.options.length > 1 && !outputs.disabled, 'Native output selector unavailable');
        const handler = new WebSocketHandler(stateManager);
        const sent = [];
        handler.socket = { readyState: WebSocket.CLOSED, bufferedAmount: 0, send(value) { sent.push(value); } };
        handler.sendAudioChunk(new Uint8Array([10, 20, 30, 40]).subarray(1, 3), false, 'system');
        assert(handler.audioBuffer.length === 1 && sent.length === 0, 'Disconnected audio lost');
        handler.socket.readyState = WebSocket.OPEN;
        handler.audioSessionReady = true;
        handler.flushAudioBuffer();
        assert([...new Uint8Array(sent[0])].join() === '2,0,20,30', 'Frame order or typed-array offset corrupted');
        handler.socket.bufferedAmount = 400000;
        for (let i = 0; i < 10; i++) handler.sendAudioChunk(new Uint8Array(60000), false, 'system');
        assert(handler.audioBuffer.reduce((size, frame) => size + frame.frame.byteLength, 0) <= 384000, 'Unbounded browser audio queue');
        handler.audioBuffer = [{ at: Date.now() - 5000, frame: new Uint8Array([2, 0, 1, 2]).buffer }];
        handler.socket.bufferedAmount = 0;
        const count = sent.length;
        handler.flushAudioBuffer();
        assert(sent.length === count && handler.audioBuffer.length === 0, 'Expired speech replayed');
        const starting = handler.startInterview();
        assert(handler.pendingStart, 'Startup did not wait for acknowledgement');
        handler.handleMessage({ type: 'interview_started', payload: { audio_capture_mode: 'native' } });
        await starting;
        const startPayload = JSON.parse(sent.find(value => typeof value === 'string'));
        assert(startPayload.payload.audioCaptureMode === 'native' && !startPayload.payload.process_all_speakers, 'Native interview defaults missing');
        const failing = handler.startInterview();
        handler.handleMessage({ type: 'interview_start_failed', payload: { message: 'Device removed' } });
        let rejected = false;
        try { await failing; } catch (error) { rejected = error.message === 'Device removed'; }
        assert(rejected && !handler.pendingStart, 'Failed startup left a pending session');
        const { startAudioProcessing, stopAudioProcessing } = await import('/static/js/audio_handler.js');
        const generator = new AudioContext({ sampleRate: 48000 });
        await generator.resume();
        const generated = generator.createMediaStreamDestination();
        const oscillator = generator.createOscillator();
        const silence = generator.createGain();
        silence.gain.value = 0;
        oscillator.connect(silence).connect(generated);
        oscillator.start();
        navigator.mediaDevices.getUserMedia = async () => generated.stream;
        let displayRequests = 0;
        navigator.mediaDevices.getDisplayMedia = async () => { displayRequests++; throw new Error('Unexpected screen request'); };
        let backups = 0;
        let silentFrames = 0;
        const backupListener = () => backups++;
        window.addEventListener('superassist:backup-audio-started', backupListener);
        window.muteManager.setMicrophoneMute(true);
        const captureStarted = await startAudioProcessing('generated-microphone', () => silentFrames++, false);
        assert(captureStarted && displayRequests === 0, 'Native mode unnecessarily requests screen sharing');
        await new Promise(resolve => setTimeout(resolve, 5600));
        assert(backups === 0, 'Muted silence triggered a false backup engine');
        assert(silentFrames > 0, 'Muted silence was dropped before STT endpointing');
        stopAudioProcessing();
        navigator.mediaDevices.getDisplayMedia = async () => new MediaStream();
        assert(!await startAudioProcessing('generated-microphone', () => {}, true), 'Video-only sharing was accepted as interview audio');
        oscillator.stop();
        await generator.close();
        window.removeEventListener('superassist:backup-audio-started', backupListener);
        switchView('preflight');
        return ['native selection', 'output devices', 'disconnected buffering', 'PCM offset', 'backpressure bound', 'expired speech', 'startup acknowledgement', 'startup failure', 'mic-only capture', 'muted silence heartbeat', 'video-only share rejection'];
    });
    await page.screenshot({ path: 'output/playwright/audio-setup.png', fullPage: true });
    return checks;
}
